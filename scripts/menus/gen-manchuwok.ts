// Generate Manchu Wok's menu from its official nutrition PDF
// (raw/manchuwok.tsv, see fetch-manchuwok.cjs).
//
// Entrées, noodles and rice are published for each portion (5 / 6 / 7 / 16 oz,
// or 8 / 9 / 10 / 16 oz for noodles and rice); those become the item's sizes.
// Manchu Wok publishes no per-ingredient values, so the default split is
// apportioned by ingredient type.
//
//   run from the repo root: gen-manchuwok.ts
import * as fs from 'fs'
import type { MealCategory, Nutrition } from '../../src/types'
import { idMaker, tagsFor, writeMenu } from './lib'

type Row = { name: string; portion: string; n: Nutrition }
const rows: Row[] = []
for (const l of fs.readFileSync('scripts/menus/raw/manchuwok.tsv', 'utf8').split(/\r?\n/)) {
  if (!l) continue
  const [name, portion, cal, fat, sodium, carbs, protein] = l.split('\t')
  const [c, f, cb, p] = [+cal, +fat, +carbs, +protein]
  // Skip rows whose macros can't belong to the calories (the guide's Spring Roll
  // row carries the chicken wings' carbs and protein).
  if (4 * cb + 4 * p + 9 * f > c * 1.5 + 20) {
    console.warn(`skipping inconsistent row: ${name} ${portion}`)
    continue
  }
  rows.push({
    name: name.replace('Monogolian', 'Mongolian').replace(/Chicken and(\S)/, 'Chicken and $1'),
    portion,
    n: { calories: c, protein: Math.round(p), carbs: Math.round(cb), fat: Math.round(f), sodium: +sodium },
  })
}

function category(name: string): MealCategory {
  if (/soup/i.test(name)) return 'Mains'
  if (/roll|chicken balls|chicken wings/i.test(name)) return /wings|balls/i.test(name) ? 'Chicken' : 'Sides'
  if (/^(fried rice|lo mein|shanghai)/i.test(name)) return 'Sides'
  return 'Mains'
}

const products = new Map<string, { versions: { label: string; n: Nutrition }[] }>()
for (const r of rows) {
  let name = r.name
  let label = r.portion ? r.portion.replace(/oz$/, ' oz') : '1 serving'
  const pcs = name.match(/^(.*) – (\d) pcs$/)
  if (pcs) [name, label] = [pcs[1], `${pcs[2]} pc`]
  if (!products.has(name)) products.set(name, { versions: [] })
  products.get(name)!.versions.push({ label, n: r.n })
}

const newId = idMaker('mw')
const items: any[] = []
for (const [name, p] of products) {
  const v = p.versions
  const def = v.find((x) => x.label === '6 oz') ?? v.find((x) => x.label === '9 oz') ?? v[0]
  const tags = tagsFor(name, def.n)
  if (/hunan|kung pao|general tso|black pepper|salt and pepper/i.test(name) && !tags.includes('spicy')) tags.push('spicy')
  if (/tofu|vegetable|chop suey|green beans$/i.test(name) && !/chicken|beef/i.test(name)) tags.push('vegetarian')
  const it: any = {
    id: newId(name),
    name,
    kind: 'fixed',
    category: category(name),
    ...(tags.length ? { tags } : {}),
    nutrition: def.n,
  }
  if (v.length > 1) {
    it.defaultSize = def.label
    it.sizes = v.map((x) => ({ label: x.label, nutrition: x.n }))
  } else {
    it.serving = /^\d+g$/.test(def.label) ? `1 bowl (${def.label})` : def.label
  }
  items.push(it)
}

writeMenu({
  file: 'manchuwok',
  exportName: 'manchuwok',
  meta: { id: 'manchu-wok', name: 'Manchu Wok', cuisine: 'Chinese · Fast food', accent: '#b91c1c', segment: 'Fast Food' },
  items,
  order: ['Mains', 'Chicken', 'Sides'],
  source: [
    "Manchu Wok — complete menu from Manchu Wok's official nutrition information",
    '(PDF linked from manchuwok.com; extracted by fetch-manchuwok.cjs). Each portion',
    'size is a published value; the default-ingredient split is apportioned by type.',
    "Generated by scripts/menus/gen-manchuwok.ts — regenerate, don't hand-edit.",
  ],
})
